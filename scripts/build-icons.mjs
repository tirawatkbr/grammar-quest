// Build site/js/icons-data.js from the Material Symbols Rounded SVG files in site/assets/icons.
// Icons: Google Material Symbols (https://fonts.google.com/icons), Apache License 2.0.
// Usage: node scripts/build-icons.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "site/assets/icons");
const out = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".svg")).sort()) {
  const svg = fs.readFileSync(path.join(dir, f), "utf8");
  const paths = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length !== 1) throw new Error(`${f}: expected 1 path, got ${paths.length}`);
  if (!svg.includes('viewBox="0 -960 960 960"')) throw new Error(`${f}: unexpected viewBox`);
  out[f.replace(/\.svg$/, "")] = paths[0];
}
let js =
  "// Material Symbols Rounded (Google Fonts, Apache License 2.0) — https://fonts.google.com/icons\n" +
  "// Generated by scripts/build-icons.mjs from site/assets/icons/*.svg. Do not edit by hand.\n" +
  "export const ICONS = {\n";
for (const [k, v] of Object.entries(out)) js += `  ${JSON.stringify(k)}: ${JSON.stringify(v)},\n`;
js += "};\n";
fs.writeFileSync(path.join(root, "site/js/icons-data.js"), js);
console.log(`${Object.keys(out).length} icons written`);
