// Generate site/data/units.js (light manifest used by the app for unlock/progress without loading every unit).
// Usage: node scripts/build-manifest.mjs
import fs from "node:fs";
import path from "node:path";
import { loadUnits, dataDir } from "./lib.mjs";

const units = await loadUnits();
const manifest = units.map(({ file, unit }) => ({
  id: unit.id,
  chapter: unit.chapter,
  title: unit.title,
  titleTh: unit.titleTh,
  file,
  summaryCount: unit.summary.length,
  lessons: unit.lessons.map((l) => ({ id: l.id, title: l.title, kind: l.kind, count: l.questions.length })),
}));
const js =
  "// Generated by scripts/build-manifest.mjs — do not edit by hand.\n" +
  "export const UNITS = " +
  JSON.stringify(manifest, null, 2) +
  ";\n";
fs.writeFileSync(path.join(dataDir, "units.js"), js);
const q = manifest.reduce((a, u) => a + u.lessons.reduce((b, l) => b + l.count, 0), 0);
console.log(`units.js: ${manifest.length} units, ${manifest.reduce((a, u) => a + u.lessons.length, 0)} lessons, ${q} questions`);
