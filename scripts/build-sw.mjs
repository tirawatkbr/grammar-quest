// Generate site/sw.js with a precache list of every file in site/ and a content hash as version.
// Usage: node scripts/build-sw.mjs
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const site = path.join(root, "site");
const files = [];
(function walk(dir) {
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, f.name);
    if (f.isDirectory()) walk(p);
    else files.push(path.relative(site, p).split(path.sep).join("/"));
  }
})(site);
const skip = new Set(["sw.js", "404.html"]);
const list = files.filter((f) => !skip.has(f) && !f.startsWith("assets/icons/") && !f.endsWith(".txt")).sort();
const hash = crypto.createHash("sha256");
for (const f of list) hash.update(f).update(fs.readFileSync(path.join(site, f)));
const version = hash.digest("hex").slice(0, 12);
const urls = ["./", ...list.map((f) => "./" + f)];
const sw = `// Generated by scripts/build-sw.mjs — do not edit by hand.
const VERSION = "${version}";
const CACHE = "gq-" + VERSION;
const PRECACHE = ${JSON.stringify(urls, null, 2)};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("gq-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener("message", (e) => {
  if (e.data && e.data.type === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return; // Firebase etc. go to network
  e.respondWith(
    caches.match(req, { ignoreSearch: true }).then(
      (hit) =>
        hit ||
        fetch(req).catch(() => (req.mode === "navigate" ? caches.match("./") : Response.error())),
    ),
  );
});
`;
fs.writeFileSync(path.join(site, "sw.js"), sw);
console.log(`sw.js: ${urls.length} files, version ${version}`);
